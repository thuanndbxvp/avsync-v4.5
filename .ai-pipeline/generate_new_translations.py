"""Generate new dictionary entries for CJK phrases that appear frequently
in user-facing files but are not yet in the dictionary.

Strategy:
- Look at CJK phrases of length 2-6 chars
- Keep only those that occur >= 3 times in the corpus
- Map each to a reasonable Vietnamese translation (using AI knowledge)
"""
import ast
import re
import json
from pathlib import Path

ROOT = Path("D:/AIWriteX")
EXCLUDE_DIRS = {
    "node_modules", ".venv", "venv", "__pycache__",
    ".git", "dist", "build", ".next", "out",
    "static/lib", ".ai-pipeline", "knowledge",
    "translations_complete.json", "translations_map.json",
    "zh_strings_full.json", "zh_audit.json",
}
CJK = re.compile(r'[一-鿿]')
SCAN_EXT = {".html", ".js", ".css"}

def should_skip(path: Path) -> bool:
    parts = set(path.parts)
    if parts & EXCLUDE_DIRS:
        return True
    name = path.name.lower()
    if any(x in name for x in ("loader.js", "tsworker.js", "marked.min.js", "i18n_middleware.py")):
        return True
    return False

# Read existing dictionary
DICT_PATH = Path("src/ai_write_x/web/i18n_middleware.py")
dict_text = DICT_PATH.read_text(encoding="utf-8")
m = re.search(r"^CJK_VI_DICTIONARY:\s*List\[Tuple\[str,\s*str\]\]\s*=\s*\[(.+?)\]", dict_text, re.DOTALL | re.MULTILINE)
list_text = "[" + m.group(1) + "]"
dict_data = ast.literal_eval(list_text)
existing = {src for src, _ in dict_data}
existing_translations = dict(dict_data)
print(f"Existing dict entries: {len(existing)}")

# Scan all files
unique_cjk: dict[str, int] = {}
for p in ROOT.rglob("*"):
    if not p.is_file():
        continue
    if should_skip(p):
        continue
    if p.suffix.lower() not in SCAN_EXT:
        continue
    try:
        text = p.read_text(encoding="utf-8")
    except Exception:
        continue
    for m2 in CJK.finditer(text):
        start = m2.start()
        end = start
        while end < len(text) and CJK.match(text[end]):
            end += 1
        phrase = text[start:end]
        if 2 <= len(phrase) <= 6:  # filter to reasonable sizes
            unique_cjk[phrase] = unique_cjk.get(phrase, 0) + 1

# Filter: not in dict, frequency >= 3
candidates = []
for phrase, count in unique_cjk.items():
    if phrase in existing:
        continue
    if count < 3:
        continue
    candidates.append((phrase, count))

print(f"Candidate new phrases (>=3 occurrences): {len(candidates)}")

